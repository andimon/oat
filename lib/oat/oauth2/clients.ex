defmodule Oat.OAuth2.Clients do
  @moduledoc """
  Client registration and authentication: RFC 6749 (https://www.rfc-editor.org/rfc/rfc6749) §2, §2.3, §3.2.1.

  Client secrets are generated by the server with 256 bits of entropy, so a
  SHA-256 hash is enough to store them safely (§10.10). The plain secret is
  returned once, at registration.
  """

  alias Oat.OAuth2.{Client, ClientAuth, Error, Syntax, Token}
  alias Oat.Repo

  @doc """
  Registers a client.

  `attrs` takes `:name`, `:redirect_uris`, `:scopes` and `:default_scopes`.
  An `:id` is generated unless given.

  Options:

    * `:confidential` (default `true`): generate a client secret. Set to
      `false` for a public client, such as a native app (§2.1).

  Returns `{:ok, client, secret}`, with `secret` `nil` for a public client.
  """
  @spec register(map(), keyword()) ::
          {:ok, Client.t(), String.t() | nil} | {:error, Ecto.Changeset.t()}
  def register(attrs, opts \\ []) do
    secret = if Keyword.get(opts, :confidential, true), do: Token.generate()

    attrs =
      attrs
      |> Map.new(fn {k, v} -> {to_string(k), v} end)
      |> Map.put_new_lazy("id", fn -> Token.generate(16) end)
      |> Map.put("secret_hash", secret && Token.hash(secret))

    with {:ok, client} <- %Client{} |> Client.changeset(attrs) |> Repo.insert(),
         do: {:ok, client, secret}
  end

  @doc """
  Fetches a client by its identifier. An identifier outside the `client_id`
  syntax (A.1) cannot belong to a client, so it is not looked up.
  """
  @spec get(String.t() | nil) :: Client.t() | nil
  def get(id), do: if(Syntax.client_id?(id), do: Repo.get(Client, id))

  @doc """
  Authenticates the client making a token request (§3.2.1).

  * `authorization` is the `Authorization` header value, or `nil`.
  * `params` are the decoded body parameters.

  A confidential client must authenticate with its secret, in the header or in
  the body. A public client identifies itself with `client_id` only.
  """
  @spec authenticate(String.t() | nil, map()) :: {:ok, Client.t()} | {:error, Error.t()}
  def authenticate(authorization, params) do
    case ClientAuth.extract(authorization, params) do
      {:ok, {method, {id, secret}}} when method in [:basic, :body] ->
        id |> get() |> check_secret(secret)

      {:ok, {:public, id}} ->
        id |> get() |> check_public()

      {:ok, :none} ->
        Error.error(:invalid_client, "Client authentication is required")

      {:error, :invalid_request} ->
        Error.error(:invalid_request, "Use only one client authentication method")

      {:error, :invalid_client} ->
        invalid_client()
    end
  end

  # client_secret is *VSCHAR (A.2); anything else cannot be a client's secret.
  defp check_secret(%Client{secret_hash: hash} = client, secret) when is_binary(hash) do
    if Syntax.client_secret?(secret) and ClientAuth.secret_matches?(Token.hash(secret), hash),
      do: {:ok, client},
      else: invalid_client()
  end

  defp check_secret(_client, _secret), do: invalid_client()

  defp check_public(%Client{} = client) do
    if Client.confidential?(client), do: invalid_client(), else: {:ok, client}
  end

  defp check_public(nil), do: invalid_client()

  defp invalid_client, do: Error.error(:invalid_client, "Client authentication failed")
end
